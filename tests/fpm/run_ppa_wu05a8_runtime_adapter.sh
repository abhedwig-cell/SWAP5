  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c     src/process/macropore/mod_ppa_wu05a6_top_inflow_limiter.f90 -o "$OUT/toplimit.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c     src/process/macropore/mod_ppa_wu05a6_vertical_flux_reconstruction.f90 -o "$OUT/vflux.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c     src/runtime/mod_macropore_continuation_state.f90 -o "$OUT/state.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c     src/process/macropore/mod_ppa_wu05a5_top_partition.f90 -o "$OUT/topa5.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c     src/process/macropore/mod_ppa_wu05a5_multi_domain_process.f90 -o "$OUT/multia5.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c     src/runtime/mod_ppa_wu05a5_macropore_restart.f90 -o "$OUT/restarta5.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c     src/process/macropore/mod_ppa_wu05a6_sorptivity_history.f90 -o "$OUT/history.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c     src/process/macropore/mod_ppa_wu05a6_rate_bundle.f90 -o "$OUT/bundle.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c src/process/macropore/mod_macropore_standard_storage.f90 -o "$OUT/stdstorage.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c src/runtime/mod_macropore_standard_rate_adapter.f90 -o "$OUT/rateadapter.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c src/process/macropore/mod_macropore_dynamic_crack.f90 -o "$OUT/dynamic_crack.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c src/solver/mod_macropore_exchange_overlay_provider.f90 -o "$OUT/overlay.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c src/runtime/mod_macropore_single_column_runtime.f90 -o "$OUT/runtime.o"
  gfortran "${FLAGS[@]}" -O"$opt" -J "$OUT" -I "$OUT" -c tests/fpm/test_ppa_wu05a8_rate_adapter.f90 -o "$OUT/test_rateadapter.o"
  gfortran -O"$opt" "$OUT/solver_contract.o" "$OUT/state.o" "$OUT/topa5.o" "$OUT/multia5.o"     "$OUT/sorp.o" "$OUT/unsat.o" "$OUT/sat.o" "$OUT/satsrc.o" "$OUT/rapid.o" "$OUT/toplimit.o"     "$OUT/vflux.o" "$OUT/history.o" "$OUT/bundle.o" "$OUT/stdstorage.o" "$OUT/rateadapter.o"     "$OUT/test_rateadapter.o" -o "$OUT/test_rateadapter"
