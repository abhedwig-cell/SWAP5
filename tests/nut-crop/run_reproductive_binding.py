#!/usr/bin/env python3
"""Affected source process binding; defaults are exercised by incumbent runners."""
import ast,base64,hashlib,io,json,os,runpy,sys,tarfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
wrapper=runpy.run_path(str(ROOT/'tests/nut-crop/run_b111_request_binding.py') if '--direct'not in sys.argv else str(ROOT/'tests/nut-crop/run_crop_supply.py'))
ns=wrapper['ns']if'--direct'not in sys.argv else wrapper
OUT=ns['OUT'];cmd=ns['cmd'];FC=ns['FC'];sha=ns['sha'];result=ns.get('result',ns.get('results'));result['reproductive']={}
# The identical immutable literal is generated by the small production test.
literal=Path(os.environ['REPRODUCTIVE_LITERAL_FILE']).resolve()
assert hashlib.sha256(literal.read_bytes()).hexdigest()==os.environ['REPRODUCTIVE_LITERAL_SHA256']
extra=[]
if '--direct'not in sys.argv:
 joint=ROOT/'tests/nut-crop/test_reproductive_joint.f90'
 ns['providers']['literal_reproductive']=literal
 start=len(ns['ordered']);ns['visit'](joint)
 extra=[p for p in ns['ordered'][start:]if p not in (joint,literal)]
 with tarfile.open(fileobj=io.BytesIO(base64.b64decode((ROOT/'integration/audits/evidence/MC_NUT01_B111_REQUEST_BINDING_SCIENCE_20261016.tar.xz.b64').read_bytes())))as a:
  for opt in ('O0','O2'):
   for name in ('b111-expected.bin','b111-restart.bin','test_crop_soil_joint-expected.bin','test_crop_soil_joint-restart.bin'):
    assert (OUT/opt/name).read_bytes()==a.extractfile('science/'+opt+'/'+name).read(), 'incumbent native drift '+name
 material_runner=ROOT/'tests/nut-senescence/run_senescence.py'
 node=next(n for n in ast.parse(material_runner.read_text()).body if isinstance(n,ast.Assign)and any(isinstance(t,ast.Name)and t.id=='oracle'for t in n.targets))
 material_oracle=ast.literal_eval(node.value)
 authority=ROOT/'integration/audits/evidence/SWAP431_B111_AUTHORITY.tar.gz.b64'
 with tarfile.open(fileobj=io.BytesIO(base64.b64decode(authority.read_bytes())))as a:
  material_raw={n:a.extractfile('SWAP/'+n).read()for n in ('wofost_soil_amendments.f90','wofost_soil_cropresidues.f90')}
 for p in (material_runner,ROOT/'tests/nut-material/material_fixture.inc'):result['input_sha256'][str(p.relative_to(ROOT))]=sha(p)
 result['material_authority']={n:hashlib.sha256(raw).hexdigest()for n,raw in material_raw.items()}
for opt in ('O0','O2'):
 b=OUT/opt;flags=[s.replace(str(OUT/'O2'),str(b))for s in ns['flags']];flags[0]='-'+opt
 objects=sorted(b.glob('provider-*.o'),key=lambda p:int(p.stem.split('-')[-1]))
 obj=b/'reproductive_literal.o';cmd(FC+flags+['-c',literal,'-o',obj],b,'driver_compile')
 driver=ROOT/'tests/nut-crop/test_b111_reproductive_day.f90';dobj=b/(driver.stem+'.o');exe=b/driver.stem
 cmd(FC+flags+['-c',driver,'-o',dobj],b,'driver_compile');cmd(FC+flags+objects+[obj,dobj,'-o',exe],b,'link')
 output=cmd([exe],b,'native');assert 'B111_REPRODUCTIVE_REAL_SOIL_CROP_CASES=72'in output
 result['reproductive'][opt]={'daily_stdout':output}
 if '--direct'not in sys.argv:
  flags+=['-I'+str(ROOT/'tests/nut-material')]
  (b/'material_oracle.inc').write_text(material_oracle)
  more=[]
  for i,p in enumerate(extra):
   obj=b/('reproductive-provider-'+str(i)+'.o');cmd(FC+flags+['-c',p,'-o',obj],b,'compile');more.append(obj)
   result['input_sha256'][str(p.relative_to(ROOT))]=sha(p)
  for n,raw in material_raw.items():
   p=b/n;p.write_bytes(raw);obj=b/(n+'.o');cmd(FC+flags+['-c',p,'-o',obj],b,'compile');more.append(obj)
  jobj=b/(joint.stem+'.o');jexe=b/joint.stem
  cmd(FC+flags+['-c',joint,'-o',jobj],b,'driver_compile')
  # obj from the literal compilation is deliberately distinct from loop locals.
  cmd(FC+flags+objects+more+[b/'reproductive_literal.o',jobj,'-o',jexe],b,'link')
  restart=b/'reproductive-restart.bin';expected=b/'reproductive-expected.bin';fresh=b/'reproductive-fresh.bin'
  original=cmd([jexe,'write',restart,expected],b,'native');continuation=cmd([jexe,'resume',restart,fresh],b,'native')
  assert 'REPRODUCTIVE_ACTUAL_RICHARDS_DELAYED_LITERAL_ATOMIC_PENDING_OPAQUE_DISK=PASS'in original
  assert expected.read_bytes()==fresh.read_bytes()==Path(str(expected)+'.opaque').read_bytes()
  negatives=['absent','old-profile','wrong-dvsnlt','wrong-dvsnt','wrong-nfixf','wrong-fntrt']
  for policy in negatives:assert 'INVALID_DISK=PASS'in cmd([jexe,'reject',restart,'unused',policy],b,'native')
  result['reproductive'][opt].update(joint_stdout=original,fresh_stdout=continuation,endpoint_sha256=sha(expected),restart_sha256=sha(restart),policy_identity_negatives=negatives)
  result['input_sha256'][str(joint.relative_to(ROOT))]=sha(joint)
 for p in (driver,Path(__file__)):result['input_sha256'][str(p.relative_to(ROOT))]=sha(p)
assert result['reproductive']['O0']==result['reproductive']['O2']
result['literal_sha256']=sha(literal)
result['cost_seconds']={c:sum(e['seconds']for e in ns['events']if e['category']==c)for c in sorted({e['category']for e in ns['events']})}
result['status']='REPRODUCTIVE_DIRECT_PASS_NOT_ADMITTED'if'--direct'in sys.argv else'REPRODUCTIVE_PHYSICAL_PASS_NOT_ADMITTED'
(OUT/'result.json').write_text(json.dumps(result,indent=2)+'\n')
print(result['status'])
